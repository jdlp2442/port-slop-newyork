    /// <summary>Axis-aligned lot / footprint rectangle in the source frame (x0,x1,z0,z1).</summary>
    [Serializable]
    public struct RectXZ
    {
        public float X0, X1, Z0, Z1;
        public RectXZ(float x0, float x1, float z0, float z1) { X0 = x0; X1 = x1; Z0 = z0; Z1 = z1; }
        public float Width  => X1 - X0;
        public float Depth  => Z1 - Z0;
        public float Area   => Mathf.Max(0f, Width) * Mathf.Max(0f, Depth);
        public Vector2 Center => new Vector2((X0 + X1) * 0.5f, (Z0 + Z1) * 0.5f);
        public RectXZ Inset(float d) => new RectXZ(X0 + d, X1 - d, Z0 + d, Z1 - d);
        public bool Overlaps(RectXZ o) => X0 < o.X1 && X1 > o.X0 && Z0 < o.Z1 && Z1 > o.Z0;
    }

    public struct StreetSeg
    {
        public float X0, X1, Z, Width;
        public int Dir;            // +1 eastbound, -1 westbound, 0 two-way
    }

    public sealed class StreetRec
    {
        public int N;
        public float Z;
        public readonly List<StreetSeg> Segs = new List<StreetSeg>();
    }

    public struct AvenueNameSpan
    {
        public float Z0, Z1;
        public string Name;
    }

    public sealed class AvenueSeg
    {
        public float Z0, Z1, W;
        public int Dir, Lanes;
        public readonly List<AvenueNameSpan> Names = new List<AvenueNameSpan>();
    }

    public sealed class AvenueRec
    {
        public string Id, Label;
        public float X;
        public readonly List<AvenueSeg> Segs = new List<AvenueSeg>();
    }

    /// <summary>Irregular block frontage frame: world = p + R_y(theta) * (local - p).</summary>
    public struct BlockFrame
    {
        public float Theta, Px, Pz;
        public RectXZ[] Rects;
    }

    public sealed class BlockRec
    {
        public int Id;
        public Vector2[] Poly;
        public RectXZ[] Lots;
        public float Park;              // 0..1 share of the island covered by parkland
        public string ParkName;
        public bool IsRect;             // curb island is an axis-aligned rectangle
        public BlockFrame[] Frames;     // null for grid blocks
        public Vector2 Center;
        public Vector4 Bounds;          // minX, maxX, minZ, maxZ
        public string District;
        public bool Median;
    }

    public sealed class RoadRec
    {
        public string Name;
        public float Width;
        public int Dir, Lanes;
        public bool Highway;
        public Vector2[] Pts;
    }

    public struct RoadLink
    {
        public int A, B, NameIdx, Dir, Lanes;
        public float Width;
        public float[] Shape;      // inner [x,z] pairs
    }

    public sealed class RoadGraphRec
    {
        public Vector2[] Nodes;
        public readonly List<RoadLink> Links = new List<RoadLink>();
        public string[] Names;
    }

    public sealed class ParkRing
    {
        public string Name;
        public Vector2[][] Rings;       // disjoint parts of one feature (NYC Parks parcels)
    }

    public sealed class ParkRec
    {
        public string Name, Category;
        public float Acres;
        public Vector2[][] Rings;       // disjoint parcels of the property
    }

    public sealed class SiteRec
    {
        public string Name;
        public float X, Z, W, D, Ang;
    }

    public sealed class PlazaRec
    {
        public string Name;
        public Vector2 A, B;
        public float Width;
    }

    public sealed class CentralParkRec
    {
        public Vector4 Bounds;          // minX, maxX, minZ, maxZ
        public Vector2[] Outline;
        public ParkRing[] Water;
        public ParkRing[] Lawns;
        public RoadRec[] Drives;
        public ParkRing[] Paths;
        public SiteRec[] Sites;
    }

    public sealed class PierRec
    {
        public string Name;
        public float Cx, Cz, Len, Wid, Ang;
        public Vector2[] Ring;
    }

    public sealed class BridgeRec
    {
        public Vector2 A, Mid;
        public Vector2 Dir;
    }

    public sealed class LandmarkRec
    {
        public string Name;
        public float X, Z, W, D, H;
        public Vector2[] Ring;
    }

    public sealed class FrameRec
    {
        public float BearingDeg;
        public float CutZ;
        public float Strip;
        public float Sidewalk;
    }

    /// <summary>
    /// Typed view of js/nyc-geodata.js (generated by tools/build-geodata.mjs).
    /// The file is a JS wrapper around one JSON object; the loader strips the wrapper so the
    /// repository artefact can be dropped into StreamingAssets untouched (no build step).
    /// </summary>
    public sealed class NycGeoData
    {
        public FrameRec Frame;
        public Vector2[] Manhattan;
        public Vector2[] UpperManhattan;
        public Vector2[] InnerShore;
        public readonly Dictionary<string, Vector2[]> Islands = new Dictionary<string, Vector2[]>();
        public readonly Dictionary<string, Vector2[][]> Boroughs = new Dictionary<string, Vector2[][]>();
        public readonly List<StreetRec> Streets = new List<StreetRec>();
        public readonly List<AvenueRec> Avenues = new List<AvenueRec>();
        public Vector2[] Broadway;
        public readonly List<PlazaRec> Plazas = new List<PlazaRec>();
        public readonly List<RoadRec> Roads = new List<RoadRec>();
        public RoadGraphRec RoadGraph;
        public readonly List<BlockRec> Blocks = new List<BlockRec>();
        public readonly List<ParkRec> Parks = new List<ParkRec>();
        public CentralParkRec CentralPark;
        public readonly List<PierRec> Piers = new List<PierRec>();
        public readonly Dictionary<string, BridgeRec> Bridges = new Dictionary<string, BridgeRec>();
        public readonly Dictionary<string, LandmarkRec> Landmarks = new Dictionary<string, LandmarkRec>();
        public readonly Dictionary<string, Vector2> Points = new Dictionary<string, Vector2>();

        // ------------------------------------------------------------------ loading

        public static NycGeoData LoadFromFile(string absolutePath) => Parse(File.ReadAllText(absolutePath));

        public static NycGeoData LoadFromStreamingAssets(string relativePath = "nyc/nyc-geodata.json")
        {
            string path = Path.Combine(Application.streamingAssetsPath, relativePath);
            if (!File.Exists(path))
            {
                string[] alternatives = new[]
                {
                    Path.Combine(Application.streamingAssetsPath, "nyc/nyc-geodata.json"),
                    Path.Combine(Application.streamingAssetsPath, "nyc-geodata.json"),
                    Path.Combine(Application.streamingAssetsPath, "nyc/nyc-geodata.js"),
                    Path.Combine(Application.streamingAssetsPath, "nyc-geodata.js")
                };
                foreach (var alt in alternatives)
                {
                    if (File.Exists(alt)) { path = alt; break; }
                }
            }
#if UNITY_ANDROID && !UNITY_EDITOR
            // StreamingAssets is inside the APK: read it with UnityWebRequest, see NycGeoDataLoader.
            throw new PlatformNotSupportedException("Use NycGeoDataLoader.LoadAsync on Android.");
#else
            return LoadFromFile(path);
#endif
        }

        public static NycGeoData Parse(string text)
        {
            if (string.IsNullOrEmpty(text)) throw new InvalidDataException("nyc-geodata: empty file");

            // Strip the JS wrapper: "(function(){ window.NYC.GEO = {...}; })();"
            if (text.TrimStart()[0] != '{')
            {
                int marker = text.IndexOf("window.NYC.GEO", StringComparison.Ordinal);
                if (marker < 0) throw new InvalidDataException("nyc-geodata: window.NYC.GEO not found");
                int eq = text.IndexOf('=', marker);
                int start = text.IndexOf('{', eq);
                int end = text.LastIndexOf("};", StringComparison.Ordinal);
                if (start < 0 || end <= start) throw new InvalidDataException("nyc-geodata: malformed payload");
                text = text.Substring(start, end - start + 1);
            }

            JObject root = JObject.Parse(text);
            var geo = new NycGeoData();

            JToken frame = root["frame"];
            geo.Frame = new FrameRec
            {
                BearingDeg = F(frame, "bearingDeg", 29.02f),
                CutZ       = F(frame, "cutZ", -7090f),
                Strip      = F(frame, "strip", 20f),
                Sidewalk   = F(frame, "sidewalk", 4.6f)
            };

            geo.Manhattan      = Flat(root["manhattan"]);
            geo.UpperManhattan = Flat(root["upperManhattan"]);
            geo.InnerShore     = Flat(root["innerShore"]);
            geo.Broadway       = Flat(root["broadway"]);

            if (root["islands"] is JObject islands)
                foreach (var p in islands.Properties()) geo.Islands[p.Name] = Flat(p.Value);

            if (root["boroughs"] is JObject boroughs)
                foreach (var p in boroughs.Properties())
                {
                    var rings = new List<Vector2[]>();
                    if (p.Value is JArray arr) foreach (var r in arr) rings.Add(Flat(r));
                    geo.Boroughs[p.Name] = rings.ToArray();
                }

            foreach (var s in Arr(root["streets"]))
            {
                var rec = new StreetRec { N = I(s, "n"), Z = F(s, "z") };
                foreach (var g in Arr(s["segs"]))
                {
                    var seg = new StreetSeg
                    {
                        X0 = g[0].Value<float>(), X1 = g[1].Value<float>(),
                        Dir = g[2].Value<int>(), Width = g[3].Value<float>(), Z = rec.Z
                    };
                    rec.Segs.Add(seg);
                }
                geo.Streets.Add(rec);
            }

            foreach (var a in Arr(root["avenues"]))
            {
                var rec = new AvenueRec { Id = a["id"]?.Value<string>(), Label = a["label"]?.Value<string>(), X = F(a, "x") };
                foreach (var s in Arr(a["segs"]))
                {
                    var seg = new AvenueSeg
                    {
                        Z0 = F(s, "z0"), Z1 = F(s, "z1"), W = F(s, "w"),
                        Dir = I(s, "dir"), Lanes = I(s, "lanes")
                    };
                    if (s["names"] is JArray names)
                        foreach (var n in names)
                            seg.Names.Add(new AvenueNameSpan { Z0 = n[0].Value<float>(), Z1 = n[1].Value<float>(), Name = n[2].Value<string>() });
                    rec.Segs.Add(seg);
                }
                geo.Avenues.Add(rec);
            }

            if (root["plazas"] is JArray plazas)
            {
                foreach (var p in plazas)
                {
                    geo.Plazas.Add(new PlazaRec
                    {
                        Name = p["name"]?.Value<string>(),
                        A = Flat2(p["a"]),
                        B = Flat2(p["b"]),
                        Width = F(p, "w")
                    });
                }
            }

            foreach (var r in Arr(root["roads"]))
            {
                geo.Roads.Add(new RoadRec
                {
                    Name = r[0].Value<string>(),
                    Width = r[1].Value<float>(),
                    Dir = r[2].Type == JTokenType.Integer ? r[2].Value<int>() : ParseDir(r[2].Value<string>()),
                    Lanes = r[3].Value<int>(),
                    Highway = r[4].Value<int>() != 0,
                    Pts = Flat(r[5])
                });
            }

            if (root["roadGraph"] is JObject rg)
            {
                geo.RoadGraph = new RoadGraphRec
                {
                    Nodes = Flat(rg["nodes"]),
                    Names = rg["names"]?.ToObject<string[]>() ?? Array.Empty<string>()
                };
                foreach (var l in Arr(rg["links"]))
                {
                    // [a, b, nameIdx, width, lanes, dir, innerShape[]]
                    var shape = new List<float>();
                    if (l.Count() > 6 && l[6] is JArray inner)
                        for (int s = 0; s < inner.Count; s++) shape.Add(inner[s].Value<float>());
                    geo.RoadGraph.Links.Add(new RoadLink
                    {
                        A = l[0].Value<int>(),
                        B = l[1].Value<int>(),
                        NameIdx = l[2].Value<int>(),
                        Width = l[3].Value<float>(),
                        Lanes = l[4].Value<int>(),
                        Dir = l[5].Value<int>(),
                        Shape = shape.ToArray()
                    });
                }
            }

            foreach (var b in Arr(root["blocks"]))
            {
                var rec = new BlockRec
                {
                    Id = geo.Blocks.Count,
                    Poly = Flat(b[0]),
                    Lots = Rects(b[1]),
                    Park = b[2].Value<float>(),
                    ParkName = b[3].Value<string>(),
                    IsRect = b[4].Value<int>() != 0,
                    Frames = ParseFrames(b[5])
                };
                ComputeBlockBounds(rec);
                rec.Median = (rec.ParkName != null && rec.ParkName.EndsWith("Malls")) ||
                             Mathf.Min(rec.Bounds.y - rec.Bounds.x, rec.Bounds.w - rec.Bounds.z) < 9f;
                geo.Blocks.Add(rec);
            }

            foreach (var p in Arr(root["parks"]))
            {
                var rings = new List<Vector2[]>();
                foreach (var r in Arr(p["rings"])) rings.Add(Flat(r));
                geo.Parks.Add(new ParkRec
                {
                    Name = p["name"]?.Value<string>(),
                    Category = p["cat"]?.Value<string>(),
                    Acres = F(p, "acres"),
                    Rings = rings.ToArray()
                });
            }

            if (root["centralPark"] is JObject cp)
            {
                var bounds = cp["bounds"];
                geo.CentralPark = new CentralParkRec
                {
                    Bounds = new Vector4(F(bounds, "minX"), F(bounds, "maxX"), F(bounds, "minZ"), F(bounds, "maxZ")),
                    Outline = Flat(cp["outline"]),
                    Water = ParseParkRings(cp["water"], "ring"),
                    Lawns = ParseParkRings(cp["lawns"], "ring"),
                    Drives = ParseDrives(cp["drives"]),
                    Paths = ParseParkRings(cp["paths"], "pts"),
                    Sites = ParseSites(cp["sites"])
                };
            }

            foreach (var p in Arr(root["piers"]))
            {
                geo.Piers.Add(new PierRec
                {
                    Name = p["name"]?.Value<string>(),
                    Cx = F(p, "cx"), Cz = F(p, "cz"), Len = F(p, "len"), Wid = F(p, "wid"), Ang = F(p, "ang"),
                    Ring = Flat(p["ring"])
                });
            }

            if (root["bridges"] is JObject bridges2)
                foreach (var p in bridges2.Properties())
                {
                    var b = p.Value;
                    geo.Bridges[p.Name] = new BridgeRec
                    {
                        A = Flat2(b["a"]), Mid = Flat2(b["mid"]), Dir = Flat2(b["dir"])
                    };
                }

            if (root["landmarks"] is JObject landmarks)
                foreach (var p in landmarks.Properties())
                {
                    var l = p.Value;
                    geo.Landmarks[p.Name] = new LandmarkRec
                    {
                        Name = p.Name, X = F(l, "x"), Z = F(l, "z"), W = F(l, "w"), D = F(l, "d"), H = F(l, "h"),
                        Ring = Flat(l["ring"])
                    };
                }

            if (root["points"] is JObject points)
                foreach (var p in points.Properties()) geo.Points[p.Name] = Flat2(p.Value);

            return geo;
        }

        // ------------------------------------------------------------------ helpers

        static void ComputeBlockBounds(BlockRec b)
        {
            float minX = float.MaxValue, maxX = float.MinValue, minZ = float.MaxValue, maxZ = float.MinValue;
            for (int i = 0; i < b.Poly.Length; i++)
            {
                var p = b.Poly[i];
                if (p.x < minX) minX = p.x;
                if (p.x > maxX) maxX = p.x;
                if (p.y < minZ) minZ = p.y;
                if (p.y > maxZ) maxZ = p.y;
            }
            b.Bounds = new Vector4(minX, maxX, minZ, maxZ);
            b.Center = new Vector2((minX + maxX) * 0.5f, (minZ + maxZ) * 0.5f);
        }

        static int ParseDir(string s) => s switch { "FT" => 1, "TF" => -1, "TW" => 0, _ => 0 };

        static BlockFrame[] ParseFrames(JToken t)
        {
            if (t == null || t.Type != JTokenType.Array) return null;
            var list = new List<BlockFrame>();
            foreach (var f in t)
            {
                list.Add(new BlockFrame
                {
                    Theta = f[0].Value<float>(),
                    Px = f[1].Value<float>(),
                    Pz = f[2].Value<float>(),
                    Rects = Rects(f[3])
                });
            }
            return list.Count > 0 ? list.ToArray() : null;
        }

        static SiteRec[] ParseSites(JToken t)
        {
            if (t is not JArray a) return Array.Empty<SiteRec>();
            var list = new List<SiteRec>();
            foreach (var s in a)
            {
                list.Add(new SiteRec
                {
                    Name = s["name"]?.Value<string>(),
                    X = F(s, "x"),
                    Z = F(s, "z"),
                    W = F(s, "w"),
                    D = F(s, "d"),
                    Ang = F(s, "ang")
                });
            }
            return list.ToArray();
        }

        static ParkRing[] ParseParkRings(JToken t, string field)
        {
            var list = new List<ParkRing>();
            foreach (var e in Arr(t))
            {
                if (e is JArray && e.First?.Type == JTokenType.Float) continue; // a bare ring
                list.Add(new ParkRing { Name = e["name"]?.Value<string>(), Rings = new[] { Flat(e[field]) } });
            }
            return list.ToArray();
        }

        static RoadRec[] ParseDrives(JToken t)
        {
            var list = new List<RoadRec>();
            foreach (var d in Arr(t))
            {
                list.Add(new RoadRec
                {
                    Name = d["name"]?.Value<string>(),
                    Width = F(d, "w", 9f),
                    Pts = Flat(d["pts"]),
                    Highway = false
                });
            }
            return list.ToArray();
        }

        static IEnumerable<JToken> Arr(JToken t) => t is JArray a ? a : Enumerable.Empty<JToken>();

        static float F(JToken o, string key, float fallback = 0f)
        {
            var v = o?[key];
            return v == null || v.Type == JTokenType.Null ? fallback : v.Value<float>();
        }

        static int I(JToken o, string key, int fallback = 0)
        {
            var v = o?[key];
            return v == null || v.Type == JTokenType.Null ? fallback : v.Value<int>();
        }

        static Vector2 Flat2(JToken t) => new Vector2(t[0].Value<float>(), t[1].Value<float>());

        static Vector2[] Flat(JToken t)
        {
            if (t is not JArray a || a.Count < 2) return Array.Empty<Vector2>();
            var r = new Vector2[a.Count / 2];
            for (int i = 0; i < r.Length; i++) r[i] = new Vector2(a[i * 2].Value<float>(), a[i * 2 + 1].Value<float>());
            return r;
        }

        static RectXZ[] Rects(JToken t)
        {
            if (t is not JArray a) return Array.Empty<RectXZ>();
            var r = new RectXZ[a.Count];
            for (int i = 0; i < r.Length; i++)
                r[i] = new RectXZ(a[i][0].Value<float>(), a[i][1].Value<float>(), a[i][2].Value<float>(), a[i][3].Value<float>());
            return r;
        }
    }
